/* =====================================================
   USK Portal – build icons
   Reads every SVG in icons/filled, icons/outline and icons/line
   and writes icons.js, which index.html and skill-passport.html load.

   Add a new icon:
     1. Export from Figma as SVG (24 × 24 frame)
     2. Put it in icons/filled, icons/outline or icons/line  (e.g. icons/filled/job.svg)
     3. Run:  node build-icons.js

   Fixed colors from Figma (#233C5A, white, ...) are changed to currentColor,
   so the icon takes the color of the place it is used in.
   ===================================================== */
const fs = require("fs");
const path = require("path");

const ROOT = __dirname;
const STYLES = { filled: "f", outline: "o", line: "l" };
const OUT = path.join(ROOT, "icons.js");

// Paint attributes that may sit on the root <svg>; they are kept on a <g> around the content
const ROOT_PAINT = ["fill", "stroke", "stroke-width", "stroke-linecap", "stroke-linejoin", "fill-rule", "clip-rule"];

const toCurrentColor = svg => svg
  .replace(/\b(fill|stroke)="(?!none"|currentColor")[^"]*"/gi, '$1="currentColor"')
  .replace(/\b(fill|stroke)\s*:\s*(?!none|currentColor)[^;"]+/gi, "$1:currentColor");

function readIcon(file) {
  const raw = fs.readFileSync(file, "utf8").replace(/<\?xml[^>]*>|<!--[\s\S]*?-->/g, "").trim();
  const m = raw.match(/<svg\b([^>]*)>([\s\S]*)<\/svg>/i);
  if (!m) throw new Error("not an SVG");
  const attrs = m[1];
  const vb = (attrs.match(/viewBox="([^"]+)"/i) || [, "0 0 24 24"])[1];
  const keep = ROOT_PAINT.map(a => (attrs.match(new RegExp(`\\s${a}="[^"]*"`, "i")) || [""])[0]).join("");
  const body = m[2].replace(/\s+/g, " ").replace(/>\s+</g, "><").trim();
  const svg = toCurrentColor(keep ? `<g${keep}>${body}</g>` : body);
  return vb === "0 0 24 24" ? { svg } : { svg, vb };
}

const icons = {};
const problems = [];
for (const [dir, key] of Object.entries(STYLES)) {
  const folder = path.join(ROOT, "icons", dir);
  if (!fs.existsSync(folder)) continue;
  for (const f of fs.readdirSync(folder).filter(f => f.toLowerCase().endsWith(".svg")).sort()) {
    const name = f.slice(0, -4).trim().toLowerCase().replace(/[\s_]+/g, "-");
    try {
      const { svg, vb } = readIcon(path.join(folder, f));
      icons[name] = icons[name] || {};
      icons[name][key] = svg;
      if (vb) icons[name].vb = vb;
    } catch (e) {
      problems.push(`icons/${dir}/${f}: ${e.message}`);
    }
  }
}

const sorted = Object.fromEntries(Object.keys(icons).sort().map(k => [k, icons[k]]));
fs.writeFileSync(OUT,
  "/* Generated by build-icons.js from the icons/ folder. Don't edit this file: change the SVG and run  node build-icons.js */\n" +
  "window.USK_ICONS = " + JSON.stringify(sorted, null, 1) + ";\n");

console.log(`icons.js: ${Object.keys(sorted).length} icons`);
problems.forEach(p => console.warn("Skipped " + p));
